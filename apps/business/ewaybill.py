"""E-way bills through Sandbox (consignor APIs) for invoices and delivery challans.

Generate, cancel (within 24 hours), update vehicle/Part-B, extend validity and consolidate trips — all through
the API, with the government rules checked before a request is sent:
* a document older than 180 days cannot get an e-way bill;
* cancellation only within 24 hours of generation, by the generator;
* extension only in the window from 8 hours before to 8 hours after expiry, and never beyond 360 days in total;
* distance can be left to the portal ("auto from PIN codes"), which then calculates it.
Portal-made bills can still be recorded by hand.
"""
